#!/usr/bin/env node
/*
 * Reads data/vehicles.csv and data/dealers.csv and writes one SVG per row:
 *   images/vehicles/<id>.svg   (path comes from the CSV "image" column)
 *   images/dealers/<id>.svg    (path comes from the CSV "logo" column)
 * It also refreshes data/data.js, an offline snapshot used when the page is opened from file://
 *   node tools/build_images.js
 * Existing non-SVG files (e.g. your own .jpg photos) are never overwritten or deleted.
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const CarArt = require(path.join(ROOT, 'js/carart.js'));

function parseCSV(text) {
  const rows = []; let row = [], f = '', q = false;
  text = text.replace(/^﻿/, '');
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n' || c === '\r') { if (c === '\r' && text[i + 1] === '\n') i++; row.push(f); f = ''; if (row.length > 1 || row[0] !== '') rows.push(row); row = []; }
    else f += c;
  }
  if (f !== '' || row.length) { row.push(f); rows.push(row); }
  const head = rows.shift().map(h => h.trim());
  return rows.map(r => Object.fromEntries(head.map((h, i) => [h, (r[i] || '').trim()])));
}
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');

const vehicles = parseCSV(read('data/vehicles.csv'));
const dealers = parseCSV(read('data/dealers.csv'));
let nv = 0, nd = 0, skipped = 0;
for (const v of vehicles) {
  const rel = v.image || ('images/vehicles/' + v.id + '.svg');
  const fullPath = path.join(ROOT, rel);
  if (!rel.endsWith('.svg') || (fs.existsSync(fullPath) && fs.readFileSync(fullPath, 'utf8').includes('data:image/'))) { skipped++; continue; }
  fs.mkdirSync(path.dirname(path.join(ROOT, rel)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, rel), CarArt.buildSVG(v)); nv++;
}
for (const d of dealers) {
  const rel = d.logo || ('images/dealers/' + d.dealer_id + '.svg');
  if (!rel.endsWith('.svg')) continue;
  fs.mkdirSync(path.dirname(path.join(ROOT, rel)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, rel), CarArt.dealerLogo(d)); nd++;
}
const snapshot = { vehicles: read('data/vehicles.csv'), dealers: read('data/dealers.csv'), zips: read('data/zipcodes.csv') };
fs.writeFileSync(path.join(ROOT, 'data/data.js'), '/* Offline snapshot of the CSV files (auto-generated by tools/build_images.js). Used only when fetch() is unavailable, e.g. file:// */\nwindow.WHEELSPAN_SNAPSHOT = ' + JSON.stringify(snapshot) + ';\n');
console.log(`vehicle images: ${nv} (kept ${skipped} custom non-SVG), dealer logos: ${nd}, snapshot refreshed`);
